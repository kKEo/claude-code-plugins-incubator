"""Shared, lazily computed state that validators ask for instead of passing it between them."""
from __future__ import annotations

from pathlib import Path
from typing import Dict, Optional

from .core import Report, anchor_ids, listed_pages, read_lines, strip_fences


class Context:
    def __init__(self, docs_root: Path, repo_root: Optional[Path], tpl: dict, rep: Report):
        self.root = docs_root
        self.repo = repo_root
        self.tpl = tpl
        self.rep = rep
        self.roles: dict = tpl["roles"]
        self.rules: dict = tpl.get("page_rules", {})
        self.books: Dict[str, str] = {}  # role -> folder, filled by the books validator
        self._listed: Dict[str, Dict[str, str]] = {}
        self._anchors: Dict[Path, set] = {}
        self._generated: Dict[Path, bool] = {}

    def book(self, role: str) -> Path:
        return self.root / self.books[role]

    def spec(self, role: str) -> dict:
        return self.roles[role]

    def listed(self, role: str) -> Dict[str, str]:
        """Pages the role's SUMMARY.md lists, whether or not the summary validator runs."""
        if role not in self._listed:
            self._listed[role] = listed_pages(self.book(role))
        return self._listed[role]

    def anchors(self, page: Path) -> Optional[set]:
        """Anchor ids of a Markdown file, or None when it is not a file."""
        key = page.resolve()
        if key not in self._anchors:
            if not key.is_file():
                return None
            self._anchors[key] = anchor_ids(read_lines(key))
        return self._anchors[key]

    def is_generated(self, page: Path) -> bool:
        """True when one of the first five lines is a `<!-- Generated by … -->` comment."""
        key = page.resolve()
        if key not in self._generated:
            marker = self.rules.get("generated_marker", "Generated by")
            clean = strip_fences(read_lines(page))
            self._generated[key] = any(marker in t and t.strip().startswith("<!--") for _, t in clean[:5])
        return self._generated[key]
