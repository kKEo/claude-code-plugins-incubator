"""Findings, the report, and the parsing helpers every validator shares."""
from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Tuple

ROMAN = ["I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X", "XI", "XII"]
LINK_RE = re.compile(r"(!?)\[([^\]]*)\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
SUMMARY_LINK_RE = re.compile(r"^(\s*)(?:[-*]\s+)?\[([^\]]+)\]\(([^)]+)\)\s*$")
HEADING_RE = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
HTML_HREF_RE = re.compile(r"href=\"([^\"]+)\"")
ID_RE = re.compile(r"""(?:id|name)=["']([^"']+)["']|\{#([^}\s]+)\}""")
WORD_RE = re.compile(r"[A-Za-z0-9]+")


@dataclass
class Finding:
    severity: str  # ERROR | WARN | INFO
    check: str
    message: str
    file: Optional[str] = None
    line: Optional[int] = None

    def fmt(self) -> str:
        loc = ""
        if self.file:
            loc = f" [{self.file}" + (f":{self.line}" if self.line else "") + "]"
        return f"{self.severity:5} {self.check:<18} {self.message}{loc}"


@dataclass
class Report:
    docs_root: str
    repo_root: Optional[str] = None
    books: Dict[str, str] = field(default_factory=dict)  # role -> folder
    findings: List[Finding] = field(default_factory=list)
    worklist: List[str] = field(default_factory=list)  # files for the qualitative pass
    generated: List[str] = field(default_factory=list)  # pages carrying the "Generated by" marker
    checks_run: List[str] = field(default_factory=list)  # validators that ran, in order
    full: bool = True  # every validator was requested

    def add(self, severity: str, check: str, message: str, file: Optional[Path] = None, line: Optional[int] = None):
        rel = None
        if file is not None:
            try:
                rel = str(Path(file).resolve().relative_to(Path(self.docs_root).resolve()))
            except ValueError:
                rel = (rel_to(file, self.repo_root) if self.repo_root else None) or str(file)
        self.findings.append(Finding(severity, check, message, rel, line))

    def error(self, *a, **k):
        self.add("ERROR", *a, **k)

    def warn(self, *a, **k):
        self.add("WARN", *a, **k)

    def info(self, *a, **k):
        self.add("INFO", *a, **k)

    def counts(self) -> Dict[str, int]:
        c = {"ERROR": 0, "WARN": 0, "INFO": 0}
        for f in self.findings:
            c[f.severity] += 1
        return c


def load_template(path: Path, docs_root: Path) -> dict:
    with open(path, encoding="utf-8") as fh:
        tpl = json.load(fh)
    override = docs_root / ".docs-template.json"
    if override.exists():
        with open(override, encoding="utf-8") as fh:
            ov = json.load(fh)
        for key, val in ov.items():
            if key == "roles":
                for role, spec in val.items():
                    tpl["roles"].setdefault(role, {}).update(spec)
            elif key == "page_rules":
                tpl["page_rules"].update(val)
            else:
                tpl[key] = val
    return tpl


def strip_fences(lines: List[str]) -> List[Tuple[int, str]]:
    """Return (lineno, text) for lines outside fenced code blocks; fenced lines become ''."""
    out = []
    fence = None
    for i, raw in enumerate(lines, 1):
        s = raw.rstrip("\n")
        m = re.match(r"^\s*(`{3,}|~{3,})", s)
        if m:
            tok = m.group(1)[0]
            if fence is None:
                fence = tok
                out.append((i, ""))
                continue
            if fence == tok:
                fence = None
                out.append((i, ""))
                continue
        out.append((i, "" if fence else s))
    return out


def slugify(text: str) -> str:
    text = re.sub(r"`([^`]*)`", r"\1", text)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = text.strip().lower()
    text = re.sub(r"[^\w\s-]", "", text)
    return re.sub(r"[\s]+", "-", text).strip("-")


def rel_to(path: Path, base: Path) -> Optional[str]:
    """POSIX path of `path` relative to `base`, or None when it lies outside (Python 3.8 safe)."""
    try:
        return Path(path).resolve().relative_to(Path(base).resolve()).as_posix()
    except ValueError:
        return None


def read_lines(p: Path) -> List[str]:
    with open(p, encoding="utf-8", errors="replace") as fh:
        return fh.readlines()


def headings(lines: List[str]) -> List[Tuple[int, int, str]]:
    hs = []
    for ln, text in strip_fences(lines):
        m = HEADING_RE.match(text)
        if m:
            hs.append((ln, len(m.group(1)), m.group(2)))
    return hs


def anchor_ids(lines: List[str]) -> set:
    """Heading slugs plus explicit <a id="…"> / {#id} anchors on a page."""
    ids = {slugify(t) for _, _, t in headings(lines)}
    for _, t in strip_fences(lines):
        for a, b in ID_RE.findall(t):
            ids.add(a or b)
    return ids


def md_files(book: Path) -> List[Path]:
    return sorted(p for p in book.rglob("*.md") if p.name != "SUMMARY.md")


def parse_summary(path: Path) -> List[Tuple[int, int, str, str]]:
    """(lineno, depth, title, target) for each link line in SUMMARY.md."""
    entries = []
    for ln, text in strip_fences(read_lines(path)):
        m = SUMMARY_LINK_RE.match(text)
        if not m:
            continue
        indent, title, target = m.groups()
        depth = len(indent.replace("\t", "  ")) // 2
        entries.append((ln, depth, title.strip(), target.strip()))
    return entries


def listed_pages(book: Path) -> Dict[str, str]:
    """{relative-path: title} of the pages SUMMARY.md lists; no findings."""
    summ = book / "SUMMARY.md"
    if not summ.exists():
        return {}
    return {target.split("#")[0]: title for _, _, title, target in parse_summary(summ)}


def match_role(folder: str, roles: dict) -> List[str]:
    f = folder.lower()
    hits = []
    for role, spec in roles.items():
        for alias in spec.get("aliases", [role]):
            if f == alias or f.startswith(alias + "-") or f.endswith("-" + alias) or f.endswith(alias):
                hits.append(role)
                break
    return hits


def body_words(clean: List[Tuple[int, str]]) -> int:
    """Words outside headings, HTML comments and code fences."""
    return sum(len(WORD_RE.findall(t)) for _, t in clean
               if t.strip() and not HEADING_RE.match(t) and not t.strip().startswith("<!--"))


def find_page(listed: Dict[str, str], keywords: List[str]) -> Optional[str]:
    """First listed page (SUMMARY order) whose title or path matches a keyword; README pages last."""
    hits = [p for p, t in listed.items() if any(k.lower() in f"{t} {p}".lower() for k in keywords)]
    hits.sort(key=lambda p: p.endswith("README.md"))
    return hits[0] if hits else None


def required_keywords(spec: dict, req_id: str) -> List[str]:
    return next((r["any_of"] for r in spec.get("required_pages", []) if r["id"] == req_id), [])
