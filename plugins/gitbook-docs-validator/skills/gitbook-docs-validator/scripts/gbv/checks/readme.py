"""readme: each book README states its audience, has a reading-map table and points to sibling books."""
from __future__ import annotations

import re

from ..context import Context
from ..core import LINK_RE, read_lines, strip_fences

DESCRIPTION = "book READMEs: audience, reading-map table, sibling-book links"


def run(ctx: Context, role: str) -> None:
    rep, book, rules = ctx.rep, ctx.book(role), ctx.rules
    readme = book / "README.md"
    if not readme.exists():
        return
    clean = strip_fences(read_lines(readme))
    text = "\n".join(t for _, t in clean)
    low = text.lower()
    if not re.search(r"(this guide is for|who this is for|is for (the )?people|is written for|for anyone who)", low):
        rep.warn("readme", f"{role} README does not state its audience ('This guide is for …')", readme)
    table_rows = [t for _, t in clean if t.strip().startswith("|") and "](" in t]
    if len(table_rows) < rules.get("readme_table_min_links", 3):
        rep.warn("readme", f"{role} README has no reading-map table with at least {rules.get('readme_table_min_links', 3)} linked rows", readme)
    others = [f for r, f in ctx.books.items() if r != role]
    if others and not any(f"../{f}/" in text for f in others):
        rep.warn("readme", f"{role} README never points readers to a sibling book (../{others[0]}/ …)", readme)
    if re.search(r"\bv\d+\.\d+(\.\d+)?\b", text) and not any("Generated by" in t for _, t in clean[:5]):
        m = re.search(r"\bv\d+\.\d+(\.\d+)?\b", text)
        rep.info("readme", f"README quotes a version ({m.group(0)}); such text drifts on each release", readme)
    # Links that leave the docs root are reported once, by the links validator (README.md is a page too).
    # Reading-map rows must route to published pages, not to files outside SUMMARY.
    listed = ctx.listed(role)
    for ln, t in clean:
        if not t.strip().startswith("|"):
            continue
        for bang, _, target in LINK_RE.findall(t):
            if bang or target.startswith(("http://", "https://", "mailto:", "#", "../")):
                continue
            path = target.split("#")[0]
            if path.endswith("/") or (book / path).is_dir():
                path = path.rstrip("/") + "/README.md"
            if path and (book / path).exists() and path not in listed:
                rep.warn("readme", f"reading-map row links {target}, which is not in SUMMARY.md (unpublished)", readme, ln)
