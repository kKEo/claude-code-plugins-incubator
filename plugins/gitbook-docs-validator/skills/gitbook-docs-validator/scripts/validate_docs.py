WORKLIST_PICKS = {"user": ["quick-start"], "operator": ["configuration"], "tester": ["running"]}


def build_worklist(docs_root: Path, tpl: dict, books: Dict[str, str], listed_by_role: Dict[str, Dict[str, str]]) -> List[str]:
    """The fixed set of files the qualitative pass reads: landing page, each README, one page per role."""
    wl = []
    landing = docs_root / tpl.get("landing_page", "index.html")
    if landing.exists():
        wl.append(landing.name)
    for role, folder in books.items():
        if (docs_root / folder / "README.md").exists():
            wl.append(f"{folder}/README.md")
    for role, folder in books.items():
        spec = tpl["roles"][role]
        for req_id in WORKLIST_PICKS.get(role, []):
            page = find_page({p: t for p, t in listed_by_role.get(role, {}).items() if p != "README.md"},
                             required_keywords(spec, req_id))
            if page and (docs_root / folder / page).is_file():
                wl.append(f"{folder}/{page}")
    return wl


GROUP_NORMALISE = [(re.compile(r"'[^']*'"), "'…'"), (re.compile(r"\S+\.(md|svg|png|jpe?g|gif|webp|html)\b\S*"), "…"),
                   (re.compile(r"\d+"), "N")]


NO_GROUP = {"stub"}  # already aggregated per book


def group_key(f: Finding) -> Tuple[str, str]:
    if f.check in NO_GROUP:
        return f.check, f"{f.file}:{f.message}"
    msg = f.message
    for rx, sub in GROUP_NORMALISE:
        msg = rx.sub(sub, msg)
    return f.check, msg


def loc(f: Finding) -> str:
    return f"`{f.file}" + (f":{f.line}" if f.line else "") + "`" if f.file else ""


def md_bullets(findings: List[Finding]) -> List[str]:
    """One bullet per finding; three or more findings of the same kind collapse into one bullet."""
    groups: Dict[Tuple[str, str], List[Finding]] = {}
    for f in findings:
        groups.setdefault(group_key(f), []).append(f)
    out = []
    for (_, _), fs in groups.items():
        if len(fs) >= 3:
            eg = ", ".join(loc(f) for f in fs[:3] if f.file)
            more = f" (+{len(fs) - 3} more)" if len(fs) > 3 else ""
            out.append(f"- {len(fs)}× {fs[0].message} — e.g. {eg}{more}")
        else:
            out.extend(f"- {loc(f) + ' — ' if f.file else ''}{f.message}" for f in fs)
    return out


SKIP_RE = re.compile(r"\b(skipped|no root README|no Makefile)\b", re.I)


def render_md(rep: Report, project: str, repo_root: Optional[Path], quiet: bool) -> str:
    c = rep.counts()
    errs = [f for f in rep.findings if f.severity == "ERROR"]
    warns = [f for f in rep.findings if f.severity == "WARN"]
    skips = [f for f in rep.findings if f.severity == "INFO" and SKIP_RE.search(f.message)]
    notes = [f for f in rep.findings if f.severity == "INFO" and f not in skips]
    verdict = "FAIL" if errs else ("PASS with deviations" if warns else "PASS")
    roles = ", ".join(f"{r}={rep.books[r]}/" if r in rep.books else f"{r}=MISSING" for r in ("user", "operator", "tester"))
    lines = [f"# Documentation template check: {project}", "",
             f"**Verdict:** {verdict} — <one sentence on why>.",
             f"Books found: {roles}",
             f"Script: {c['ERROR']} error(s), {c['WARN']} warning(s), {c['INFO']} note(s).", "",
             "## Structural failures (must fix)"]
    lines += md_bullets(errs) or ["- None."]
    lines += ["", "## Template deviations (judge)"]
    lines += md_bullets(warns) or ["- None from the script."]
    lines += ["<!-- add deviations from the qualitative pass; say whether each is reasonable -->", "", "## Suggestions"]
    if not quiet:
        lines += md_bullets(notes)
    lines += ["<!-- add improvements beyond the template -->", "", "## Not checked"]
    lines += [f"- {f.message}" for f in skips]
    if not repo_root:
        lines.append("- Repository integration (root README, Makefile, workflows): no --repo-root given.")
    lines.append("- Built output: the books were not built with mdBook/GitBook; this is a static check.")
    return "\n".join(lines)


# ----------------------------------------------------------------------------- main

def run(docs_root: Path, repo_root: Optional[Path], tpl_path: Path) -> Report:
    rep = Report(str(docs_root), str(repo_root) if repo_root else None)
    if not docs_root.is_dir():
        rep.error("root", f"{docs_root} is not a directory")
        return rep
    tpl = load_template(tpl_path, docs_root)
    roles = tpl["roles"]
    rules = tpl.get("page_rules", {})

    candidates = sorted(p.parent for p in docs_root.glob("*/SUMMARY.md"))
    if not candidates:
        rep.error("books", f"no book (directory with SUMMARY.md) under {docs_root}")
    books: Dict[str, str] = {}
    unmapped = []
    for b in candidates:
        hits = match_role(b.name, roles)
        if len(hits) == 1:
            if hits[0] in books:
                rep.error("books", f"two books map to role '{hits[0]}': {books[hits[0]]}/ and {b.name}/", b)
            else:
                books[hits[0]] = b.name
        elif len(hits) > 1:
            rep.error("books", f"book {b.name}/ matches several roles ({', '.join(hits)}); rename it or add .docs-template.json aliases", b)
        else:
            unmapped.append(b.name)
    for u in unmapped:
        rep.error("books", f"book {u}/ matches no role; the template has exactly three books (user, operator, tester). Rename it or add an alias in .docs-template.json", docs_root / u)
    for role in roles:
        if role not in books:
            rep.error("books", f"no {role} book: {roles[role].get('purpose', '')}")
    rep.books = books

    check_landing(docs_root, tpl, rep, books)
    listed_by_role: Dict[str, Dict[str, str]] = {}
    for role, folder in books.items():
        book = docs_root / folder
        spec = roles[role]
        check_book_files(book, role, rep)
        listed = check_summary(book, role, spec, rules, rep)
        listed_by_role[role] = listed
        check_pages(book, docs_root, listed, rules, rep, books)
        check_readme(book, role, rep, books, rules, listed)
        check_roles(book, role, spec, listed, rep)
    rep.worklist = build_worklist(docs_root, tpl, books, listed_by_role)
    if repo_root:
        check_repo(repo_root, docs_root, books, rep)
    return rep


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("docs_root", help="directory holding index.html and the book folders (e.g. docs/guide)")
    ap.add_argument("--repo-root", help="repository root for integration checks (README, Makefile, workflows)")
    ap.add_argument("--template", default=str(DEFAULT_TEMPLATE), help="role/template definition JSON")
    ap.add_argument("--format", choices=("text", "md", "json"), default="text",
                    help="text listing (default), md report skeleton, or json")
    ap.add_argument("--json", action="store_true", help="same as --format json")
    ap.add_argument("--worklist", action="store_true", help="also list the files to read for the qualitative pass")
    ap.add_argument("--quiet", action="store_true", help="hide INFO findings in text output")
    args = ap.parse_args(argv)
    fmt = "json" if args.json else args.format

    docs_root = Path(args.docs_root)
    repo_root = Path(args.repo_root) if args.repo_root else None
    rep = run(docs_root, repo_root, Path(args.template))
    counts = rep.counts()
    worklist_lines = []
    if args.worklist:
        worklist_lines = ["", "---- worklist for the qualitative pass (not part of the report) ----"]
        worklist_lines += [f"read: {rep.docs_root.rstrip('/')}/{w}" for w in rep.worklist]
        worklist_lines += [f"generated (check for hand edits): {rep.docs_root.rstrip('/')}/{g}" for g in rep.generated]
    if fmt == "json":
        out = {"docs_root": rep.docs_root, "books": rep.books, "counts": counts,
               "findings": [asdict(f) for f in rep.findings]}
        if args.worklist:
            out["worklist"] = rep.worklist
            out["generated"] = rep.generated
        print(json.dumps(out, indent=2))
    elif fmt == "md":
        project = (repo_root or docs_root).resolve().name
        if not repo_root and docs_root.resolve().name in ("guide", "docs", "handbook", "book", "books"):
            project = next((p.name for p in docs_root.resolve().parents if p.name not in ("guide", "docs")), project)
        print(render_md(rep, project, repo_root, args.quiet))
        print("\n".join(worklist_lines))
    else:
        print(f"docs root: {rep.docs_root}")
        print("books:     " + (", ".join(f"{r}={f}/" for r, f in rep.books.items()) or "none"))
        print()
        order = {"ERROR": 0, "WARN": 1, "INFO": 2}
        for f in sorted(rep.findings, key=lambda f: (order[f.severity], f.check, f.file or "", f.line or 0)):
            if args.quiet and f.severity == "INFO":
                continue
            print(f.fmt())
        print()
        print(f"summary: {counts['ERROR']} error(s), {counts['WARN']} warning(s), {counts['INFO']} note(s)")
        print("verdict: " + ("FAIL (fix the errors; warnings are template deviations to judge)" if counts["ERROR"] else "PASS (structure follows the template; review the warnings)"))
        if worklist_lines:
            print("\n".join(worklist_lines))
    return 1 if counts["ERROR"] else 0


if __name__ == "__main__":
    sys.exit(main())
